// -----------------------------------------------------------------------------
// 文件: Services/WebRuntimeInfo.cs
// 层级: UI 层 — Blazor Server
// 作用: 记录本进程「实际」在用的端口，供界面显示。
//
// 为什么需要它:
//   设置页要显示"当前实际监听的是哪个端口"，有三个候选来源，只有一个是对的：
//     · 配置文件——改过端口但还没重启时，配置是新值、实际跑的是旧值，
//       拿它当"当前"会与现实矛盾；
//     · 浏览器地址栏（Nav.BaseUri）——本机直连时碰巧正确，
//       但经反向代理访问时拿到的是<b>代理</b>的端口（https 就是 443），
//       于是页面显示"当前实际监听 443"、局域网地址也拼成 192.168.x.x:443，
//       全是不存在的地址；更糟的是端口输入框被预填成 443，
//       操作员顺手点保存，下次启动就会去绑 443。
//     · 启动时真正解析出来的值——只有它任何情况下都对。
//   本类就是把第三个值带到界面上。
// -----------------------------------------------------------------------------

namespace CommunicationKernel.UI.WebMaster.Services;

/// <summary>本进程启动时实际采用的端口。启动后不再变化。</summary>
/// <param name="ListenPort">Web 界面监听的端口。</param>
/// <param name="GrpcPort">内嵌 Hosting.App 的 gRPC 端口，供 WPF 上位机连接。</param>
public sealed record WebRuntimeInfo(int ListenPort, int GrpcPort);

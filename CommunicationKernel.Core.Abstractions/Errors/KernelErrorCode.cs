// 层级: Core.Abstractions / Errors
// 作用: 定义内核统一错误码，贯穿传输、协议、路由、插件各层。
// -----------------------------------------------------------------------------

namespace CommunicationKernel.Core.Abstractions.Errors;

/// <summary>
/// 内核统一错误码。各层通过 <c>OperationResult.ErrorCode</c> 上报失败原因，
/// 避免用异常类型或字符串比对跨层传递语义。
/// </summary>
public enum KernelErrorCode {
    // ============================================================================
    // 通用（0–99）
    // ============================================================================

    /// <summary>无错误。成功结果固定使用此值。</summary>
    None = 0,

    /// <summary>未分类失败。仅在无法归入更具体码时使用，便于发现漏映射。</summary>
    Unknown = 1,

    /// <summary>等待 PLC 响应超时（首字节未到或帧未读完）。上层可据此触发重连。</summary>
    Timeout = 2,

    /// <summary>调用方主动取消。不得报成 Timeout / TransportIoError，否则会引发重连风暴。</summary>
    Cancelled = 3,

    /// <summary>参数非法（端点、地址、长度等）。属配置问题，重试无意义。</summary>
    InvalidArgument = 4,

    // ============================================================================
    // 传输层（100–199）
    // ============================================================================

    /// <summary>找不到对应传输插件，或介质当前不可用。</summary>
    TransportUnavailable = 100,

    /// <summary>传输 I/O 失败（连接断开、远端关闭、读写异常）。上层可据此触发重连。</summary>
    TransportIoError = 101,

    // ============================================================================
    // 协议层（200–299）
    // ============================================================================

    /// <summary>找不到对应协议插件（protocol_id 未加载或拼写错误）。</summary>
    ProtocolNotFound = 200,

    /// <summary>协议帧非法、超限或解析失败。属报文问题，不是传输中断。</summary>
    ProtocolError = 201,

    // ============================================================================
    // 路由层（300–399）
    // ============================================================================

    /// <summary>目标路由未注册或已被移除。</summary>
    RouteNotFound = 300,

    /// <summary>同路由上已有在途请求，被 I/O 门挡住（同路由串行）。</summary>
    RouteBusy = 301,

    // ============================================================================
    // 插件加载（400–499）
    // ============================================================================

    /// <summary>指定插件不存在于目录或清单中。</summary>
    PluginNotFound = 400,

    /// <summary>插件程序集加载失败（依赖缺失、损坏等）。</summary>
    PluginLoadFailed = 401,

    /// <summary>插件声明的 API 版本与内核不兼容，拒绝加载以免运行时契约错位。</summary>
    PluginApiVersionMismatch = 402,

    /// <summary>插件隔离上下文出错（卸载、跨边界类型泄漏等）。</summary>
    PluginIsolationError = 403
}
